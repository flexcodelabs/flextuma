package com.flexcodelabs.flextuma.core.entities.whatsapp;

import com.fasterxml.jackson.annotation.JsonIgnore;
import com.fasterxml.jackson.annotation.JsonProperty;
import com.flexcodelabs.flextuma.core.entities.base.Owner;
import com.flexcodelabs.flextuma.core.helpers.MaskingUtil;
import com.flexcodelabs.flextuma.core.security.EncryptedStringConverter;
import jakarta.persistence.Column;
import jakarta.persistence.Convert;
import jakarta.persistence.Entity;
import jakarta.persistence.Table;
import jakarta.validation.constraints.NotBlank;
import lombok.AllArgsConstructor;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

import java.time.LocalDateTime;

/**
 * One Meta (Facebook) business app. Meta configures the WhatsApp webhook callback URL once per
 * app (App Dashboard → WhatsApp → Configuration), and every WhatsApp Business Account subscribed
 * to that app -- with all of its phone numbers -- posts to that single URL, signed with the app's
 * secret. Linking several {@link WhatsAppWebhookConfig}s to one of these gives them a shared
 * {@link #metaCallbackUrl}; inbound events are routed to the right config by
 * {@code metadata.phone_number_id} (or the WABA id in {@code entry[].id} for account-level events).
 */
@Entity
@Table(name = "whatsapp_meta_app")
@Getter @Setter @NoArgsConstructor @AllArgsConstructor
public class WhatsAppMetaApp extends Owner {
    public static final String PLURAL = "whatsappMetaApps";
    public static final String NAME_PLURAL = "WhatsApp Meta Apps";
    public static final String NAME_SINGULAR = "WhatsApp Meta App";

    @NotBlank
    @Column(name = "name", nullable = false)
    private String name;

    /** Meta App ID from the App Dashboard; informational, helps users match this to Meta. */
    @Column(name = "meta_app_id")
    private String metaAppId;

    @JsonProperty(access = JsonProperty.Access.WRITE_ONLY)
    @Column(name = "verify_token", nullable = false)
    @Convert(converter = EncryptedStringConverter.class)
    private String verifyToken;

    /** Meta App Secret used to validate X-Hub-Signature-256 for every event on the shared URL. */
    @JsonProperty(access = JsonProperty.Access.WRITE_ONLY)
    @Column(name = "app_secret")
    @Convert(converter = EncryptedStringConverter.class)
    private String appSecret;

    @JsonIgnore
    @Column(name = "callback_token", nullable = false, unique = true)
    private String callbackToken;

    /** The shared Meta callback URL generated by Flextuma; paste this once into the Meta app. */
    @Column(name = "meta_callback_url", nullable = false, columnDefinition = "TEXT")
    private String metaCallbackUrl;

    @Column(name = "last_verified_at")
    private LocalDateTime lastVerifiedAt;

    @Column(name = "last_event_at")
    private LocalDateTime lastEventAt;

    @JsonProperty("verifyToken") public String getMaskedVerifyToken() { return MaskingUtil.mask(verifyToken); }
    @JsonProperty("appSecret") public String getMaskedAppSecret() { return MaskingUtil.mask(appSecret); }
}
